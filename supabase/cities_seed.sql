insert into cities (key, country_id, name_en, name_ru, latitude, longitude, is_active)
select
  seed.key,
  countries.id,
  seed.name_en,
  nullif(seed.name_ru, ''),
  seed.latitude,
  seed.longitude,
  true
from seed
join countries on upper(trim(countries.iso2_code)) = seed.country_iso
on conflict (key) do update set
  country_id = excluded.country_id,
  name_en = excluded.name_en,
  name_ru = excluded.name_ru,
  latitude = excluded.latitude,
  longitude = excluded.longitude,
  is_active = excluded.is_active,
  updated_at = now();
